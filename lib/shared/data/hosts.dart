String? getFaviconHost(String url) {
  final String? host = Uri.tryParse(url)?.host;
  if (host == null || host.isEmpty) return null;
  final String name = host.toLowerCase().replaceFirst(RegExp(r'^www\.'), '');
  if (faviconHosts.contains(name)) return name;
  if (faviconAliases[name] case final alias?) return alias;
  final int dot = name.indexOf('.');
  if (dot < 0 || dot == name.lastIndexOf('.')) return null;
  final String parent = name.substring(dot + 1);
  if (faviconHosts.contains(parent)) return parent;
  return faviconAliases[parent];
}
