/// Translates [text] into the active UI language.
///
/// Returns [text] unchanged when the active language is English or when no
/// translation exists for it.
String t(String text) {
  if (appLanguage.value != AppLanguage.chinese) {
    return text;
  }
  return zh[text] ?? text;
}

/// Translates a template containing `{name}` placeholders into the active
/// UI language and substitutes the given [params].
String tf(String template, {Map<String, Object?> params = const {}}) {
  String text = t(template);
  for (final entry in params.entries) {
    text = text.replaceAll('{${entry.key}}', '${entry.value}');
  }
  return text;
}
